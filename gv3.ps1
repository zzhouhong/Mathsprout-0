function DrawMap($tn, $br, $op) {
    $wi=820;$he=500
    $bm=New-Object System.Drawing.Bitmap($wi,$he)
    $g=[System.Drawing.Graphics]::FromImage($bm)
    $g.SmoothingMode="HighQuality";$g.TextRenderingHint="AntiAlias"
    $g.Clear([System.Drawing.Color]::White)
    $fR=New-Object System.Drawing.Font("Microsoft YaHei",12,[System.Drawing.FontStyle]::Bold)
    $fB=New-Object System.Drawing.Font("Microsoft YaHei",9.5,[System.Drawing.FontStyle]::Bold)
    $fL=New-Object System.Drawing.Font("Microsoft YaHei",7.5)
    $co=@([System.Drawing.Color]::FromArgb(68,114,196),[System.Drawing.Color]::FromArgb(237,125,49),[System.Drawing.Color]::FromArgb(112,173,71),[System.Drawing.Color]::FromArgb(192,0,200))
    $pe=New-Object System.Drawing.Pen([System.Drawing.Color]::FromArgb(160,160,160),2)
    $bRt=New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(47,84,150))
    $bBg=New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(220,232,248))
    $bBl=New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(50,50,50))
    $bGr=New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(110,110,110))

    $rs=$g.MeasureString($tn,$fR);$rx=($wi-$rs.Width)/2-12;$ry=8
    $rw=$rs.Width+24;$rh=32
    $g.FillRectangle($bBg,$rx,$ry,$rw,$rh)
    $g.DrawRectangle($pe,$rx,$ry,$rw,$rh)
    $g.DrawString($tn,$fR,$bRt,$rx+12,$ry+7)
    $rcx=$rx+$rw/2;$rbot=$ry+$rh
    $bc=$br.Count;$bw=[Math]::Floor(($wi-30)/$bc)

    for($bi=0;$bi -lt $bc;$bi++){
        $b=$br[$bi];$c=$co[$bi%4]
        $pc=New-Object System.Drawing.Pen($c,2);$bc2=New-Object System.Drawing.SolidBrush($c)
        $bl=New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(248,248,255))
        $bx=8+$bi*$bw;$bw2=$bw-6
        $sz=$g.MeasureString($b.Title,$fB)
        $btX=$bx+[Math]::Max(0,($bw2-$sz.Width)/2-6)
        $btW=$sz.Width+14;$btY=$rbot+18;$btH=26
        $g.FillRectangle($bl,$btX,$btY,$btW,$btH)
        $g.DrawRectangle($pc,$btX,$btY,$btW,$btH)
        $g.DrawString($b.Title,$fB,$bc2,$btX+7,$btY+5)
        $g.DrawLine($pe,$rcx,$rbot,$btX+$btW/2,$btY)
        $sy=$btY+$btH+6
        foreach($gr in $b.Groups){
            if($sy+28 -gt $he-6){break}
            $g.DrawString($gr.Name,$fL,$bc2,$bx+3,$sy);$sy+=16
            if($gr.Items.Count -gt 0){
                $it=[string]::Join("  ",$gr.Items[0..[Math]::Min($gr.Items.Count-1,6)])
                $g.DrawString($it,$fL,$bGr,$bx+6,$sy);$sy+=16
            }
            $sy+=2
        }
        $pc.Dispose();$bc2.Dispose();$bl.Dispose()
    }
    $fR.Dispose();$fB.Dispose();$fL.Dispose();$pe.Dispose()
    $bRt.Dispose();$bBg.Dispose();$bBl.Dispose();$bGr.Dispose()
    $g.Dispose();$bm.Save($op,[System.Drawing.Imaging.ImageFormat]::Png);$bm.Dispose()
}

function BuildDoc($outPath, $docTitle, $entries) {
    Copy-Item $tp $outPath -Force
    $d=$w.Documents.Open($outPath)
    $t=$d.Tables.Item(1)

    # Fill first entry (rows 2-7)
    $e=$entries[0]
    $t.Cell(2,2).Range.Text="中审议时间："+$e.Date
    $t.Cell(3,2).Range.Text="主题名称："+$e.Theme
    $t.Cell(4,2).Range.Text="（一）兴趣`r`n"+($e.Interest -join "`r`n")+"`r`n`r`n（二）能力`r`n"+($e.Ability -join "`r`n")
    $t.Cell(5,2).Range.Text="有生成活动：`r`n"+($e.Generated -join "`r`n")
    # Clear old image, insert new mind map
    $sh=$t.Cell(6,2).Range.InlineShapes
    while($sh.Count -gt 0){$sh.Item(1).Delete()}
    $rg=$t.Cell(6,2).Range;$rg.Collapse(0)
    $mp="$td\$($docTitle)_e1.png"
    DrawMap $e.MapTitle $e.MapBranches $mp
    $d.InlineShapes.AddPicture($mp,$false,$true,$rg)
    $t.Cell(7,2).Range.Text="问题：`r`n"+($e.Problems -join "`r`n")+"`r`n`r`n解决方法：`r`n"+($e.Solutions -join "`r`n")

    # Add remaining entries
    for($i=1;$i -lt $entries.Count;$i++){
        $e=$entries[$i];$lr=$t.Rows.Count
        for($j=0;$j -lt 7;$j++){$t.Rows.Add()}
        # Header row with gray bg
        $t.Cell($lr+1,1).Range.Text="中审议时间"
        $t.Cell($lr+1,2).Range.Text=$e.Date
        try{$t.Cell($lr+1,1).Shading.BackgroundPatternColor=15132390;$t.Cell($lr+1,2).Shading.BackgroundPatternColor=15132390}catch{}
        # Theme name
        $t.Cell($lr+2,1).Range.Text="主题名称"
        $t.Cell($lr+2,2).Range.Text=$e.Theme
        # Behavior
        $t.Cell($lr+3,1).Range.Text="幼儿在主题中`r`n的行为表现`r`n（兴趣、能力、`r`n困惑、感受等）"
        $t.Cell($lr+3,2).Range.Text="（一）兴趣`r`n"+($e.Interest -join "`r`n")+"`r`n`r`n（二）能力`r`n"+($e.Ability -join "`r`n")
        # Generated
        $t.Cell($lr+4,1).Range.Text="主题实施中是否`r`n有生成的活动？"
        $t.Cell($lr+4,2).Range.Text="有生成活动：`r`n"+($e.Generated -join "`r`n")
        # Network map
        $t.Cell($lr+5,1).Range.Text="主题实施中重新`r`n架构的主题网络图"
        $sh=$t.Cell($lr+5,2).Range.InlineShapes
        while($sh.Count -gt 0){$sh.Item(1).Delete()}
        $rg=$t.Cell($lr+5,2).Range;$rg.Collapse(0)
        $mp="$td\$($docTitle)_e$($i+1).png"
        DrawMap $e.MapTitle $e.MapBranches $mp
        $d.InlineShapes.AddPicture($mp,$false,$true,$rg)
        # Problems
        $t.Cell($lr+6,1).Range.Text="主题行进是否有`r`n遇到问题和困难？`r`n有什么问题？`r`n如何解决？"
        $t.Cell($lr+6,2).Range.Text="问题：`r`n"+($e.Problems -join "`r`n")+"`r`n`r`n解决方法：`r`n"+($e.Solutions -join "`r`n")
        Write-Output "  Entry $($i+1) done"
    }

    # Title row
    $t.Cell(1,1).Range.Text="小四班 主题中审议调整单 — "+$docTitle
    $t.Cell(1,1).Range.Font.Name="楷体";$t.Cell(1,1).Range.Font.Size=16;$t.Cell(1,1).Range.Font.Bold=$true

    $d.Save();$d.Close()
}

